/**
 * بديلٌ لمُترجِمات الشوكات الأخرى في إضافات المجتمع.
 *
 * ── المشكلة ───────────────────────────────────────────────────────────
 * إضافةٌ من شوكةٍ أخرى تستورد مُترجِمها: `../autoTranslateNightcord` مثلاً،
 * وهو ملفٌّ **خارج مجلّد الإضافة** فلا يصل مع المجلّد المُستورَد. النتيجة:
 * الإضافة سليمة تماماً وتسقط عند أوّل سطر بسبب ملفٍّ لا علاقة له بعملها.
 *
 * ── لماذا هذا البديل **أمينٌ لا مخترَع** ──────────────────────────────
 * قرأتُ مصدر مُترجِم نايت‑كورد (‏2 MB): عقده `t(key: string): string`،
 * وأوّل سطرٍ فيه `if (lang === "en") return key;` — أي أنّ **سلوكه لكلّ من
 * لغته إنجليزية هو إرجاع المفتاح نفسه**. فالبديل هنا يفعل ما يفعله الأصل
 * حرفياً لتلك الحال، لا شيئاً ابتكرتُه.
 *
 * 🔴 **ولا يُوصَل بـ`@utils/esharqI18n`**: عقدها `t(ar, en)` بوسيطين، فتمريرُ
 * وسيطٍ واحد يُرجع `undefined` حين تكون العربية مفعّلة — فتُعرَض نصوص فارغة
 * بدل نصوصٍ إنجليزية. التشابه في الاسم لا يعني تشابهاً في العقد.
 *
 * 🔴 **ولا يُطبَّق صامتاً**: تقرير التوافق يُعلن الاستبدال قبل التفعيل، فيرى
 * صاحب الجهاز أنّ نصوص الإضافة ستبقى إنجليزية ويقرّر هو.
 */

/** يُرجع المفتاح كما هو — سلوك الأصل نفسه حين تكون اللغة إنجليزية. */
export function t(key: string): string {
    return key;
}

/**
 * الاسم الذي تستعمله بعض الشوكات لنفس الدالّة (`@api/pluginI18n`).
 *
 * 🔴 الاسم جزءٌ من العقد: توجيه الوحدة إلى هذا الملفّ بلا تصدير `tPlugin`
 * يترك `tPlugin` غير مُعرَّفة، فتسقط الإضافة كما لو لم تُوجَّه أصلاً.
 * وقُرئ مصدرهم: `tPlugin(key)` تُرجع المفتاح حين تكون اللغة إنجليزية —
 * نفس عقد `t` حرفاً بحرف.
 */
export const tPlugin = t;

/** الشكل الخطّافيّ الذي تستعمله بعض إضافاتهم. */
export function useTranslation() {
    return { t, lang: "en" as const };
}

export default { t, tPlugin, useTranslation };

export const SPRING = "cubic-bezier(0.22, 1.2, 0.36, 1)";

/** منحنى الخروج — بلا تجاوز: ما يختفي لا يتباهى. */
export const EASE_OUT = "cubic-bezier(0.33, 1, 0.68, 1)";

/** مدد موحّدة (مللي ثانية) — الأصغر للمسّ المباشر، والأكبر للدخول. */
export const DURATION = { tap: 90, hover: 140, enter: 220 } as const;

/** تأخير كل عنصر عن سابقه في الدخول المتتابع. */
export const STAGGER_MS = 45;

/**
 * أسلوب التتابع لعنصر رقم `index`.
 *
 * 🔴 التأخير **مسقوف**: بلا سقف يصير العنصر الثلاثون بعد ثانية ونصف، فيبدو
 * العميل بطيئاً لا أنيقاً. بعد السقف تدخل البقيّة معاً — ولا يلاحظ أحد.
 */
export function stagger(index: number, max = 8): React.CSSProperties {
    return { animationDelay: `${Math.min(index, max) * STAGGER_MS}ms` };
}

/**
 * عدّاد يتسلّق إلى قيمته بدل أن يقفز.
 *
 * يُستعمل للأرقام التي تُقرأ لا للتي تتغيّر كل لحظة: الرقم القافز يُقرأ
 * فوراً لكنه لا يقول إنه تغيّر؛ والمتسلّق يشدّ العين إلى ما تبدّل.
 *
 * 🔴 يعيد القيمة النهائية فوراً لمن طلب تقليل الحركة، وللأرقام الصغيرة
 * (أقلّ من 3) — تسلّق من 0 إلى 2 يبدو عطلاً لا حركة.
 */
export function countUpFrames(target: number, durationMs = 520): number[] {
    if (target < 3) return [target];

    const frames: number[] = [];
    const steps = Math.max(2, Math.round(durationMs / 16));

    for (let i = 1; i <= steps; i++) {
        // تسارع ثمّ تباطؤ (منحنى تكعيبي خارج) — ينتهي دقيقاً على الهدف.
        const progress = 1 - Math.pow(1 - i / steps, 3);
        frames.push(Math.round(target * progress));
    }
    return frames;
}
